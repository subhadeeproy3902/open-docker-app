"""Schema editing for PostgreSQL and MySQL / MariaDB (docs/GAPS.md): create a table, add / rename / drop a column,
add an index. Each dialog shows the exact SQL it will run, and runs it only with "Allow changes" on."""
from gi.repository import Adw, Gtk

from .db import _bq, _qi
from .util import bg, follow_content

TYPES = {"postgres": ["text", "integer", "bigint", "boolean", "numeric(12,2)", "timestamptz", "date", "jsonb", "uuid",
                      "bytea", "real", "varchar(255)"],
         "mysql": ["varchar(255)", "text", "int", "bigint", "boolean", "decimal(12,2)", "datetime", "date", "json",
                   "blob", "double"]}


def supported(backend):
    return backend.kind in TYPES


def q(backend, name):
    return _qi(name) if backend.kind == "postgres" else _bq(name)


def table_sql(backend, node):
    """The table of a tree node as SQL, e.g. "public"."orders" or `orders`."""
    if backend.kind == "postgres":
        s, t = node.ref
        return f"{_qi(s)}.{_qi(t)}"
    return _bq(node.ref)


def schema_of(backend, node):
    if backend.kind == "postgres" and node is not None and isinstance(node.ref, tuple):
        return node.ref[0]
    return "public"


def create_table(backend, schema, name, cols):
    """cols: [(name, type, nullable, primary key)]."""
    ident = (f"{_qi(schema)}.{_qi(name)}" if backend.kind == "postgres" else _bq(name))
    parts = []
    for cn, ct, null, pk in cols:
        if backend.kind == "postgres" and pk and ct in ("integer", "bigint"):
            ct += " generated by default as identity"
        elif backend.kind == "mysql" and pk and ct in ("int", "bigint"):
            ct += " auto_increment"
        parts.append(f"{q(backend, cn)} {ct}" + ("" if null or pk else " not null"))
    pks = [q(backend, cn) for cn, _t, _n, pk in cols if pk]
    if pks:
        parts.append(f"primary key ({', '.join(pks)})")
    return f"create table {ident} (\n  " + ",\n  ".join(parts) + "\n)"


def add_column(backend, table, name, ctype, nullable, default):
    sql = f"alter table {table} add column {q(backend, name)} {ctype}"
    if default:
        sql += f" default {default}"
    if not nullable:
        sql += " not null"
    return sql


def rename_column(backend, table, old, new):
    return f"alter table {table} rename column {q(backend, old)} to {q(backend, new)}"


def drop_column(backend, table, name):
    return f"alter table {table} drop column {q(backend, name)}"


def add_index(backend, table, name, cols, unique):
    cl = ", ".join(q(backend, c) for c in cols)
    return f"create {'unique ' if unique else ''}index {q(backend, name)} on {table} ({cl})"


class SchemaDialog(Adw.Dialog):
    """action: table · add · rename · drop · index. columns: the current table's column names."""
    TITLES = {"table": "New table", "add": "Add a column", "rename": "Rename a column", "drop": "Drop a column",
              "index": "Add an index"}

    def __init__(self, explorer, action, columns=()):
        super().__init__(title=self.TITLES[action], content_width=560)
        self.ex, self.b, self.action, self.columns = explorer, explorer.b, action, list(columns)
        tv = Adw.ToolbarView()
        hb = Adw.HeaderBar(show_end_title_buttons=False, show_start_title_buttons=False)
        cancel = Gtk.Button(label="Cancel")
        cancel.connect("clicked", lambda *_: self.close())
        hb.pack_start(cancel)
        self.go = Gtk.Button(label="Run")
        self.go.add_css_class("destructive-action" if action == "drop" else "suggested-action")
        self.go.connect("clicked", lambda *_: self._run())
        hb.pack_end(self.go)
        tv.add_top_bar(hb)
        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=14, margin_start=18, margin_end=18, margin_bottom=18)
        self.g = Adw.PreferencesGroup()
        box.append(self.g)
        self.rows = []
        getattr(self, f"_build_{action}")()
        self.sql = Gtk.Label(xalign=0, wrap=True, selectable=True, css_classes=["monospace", "card"])
        self.sql.set_margin_top(4)
        box.append(Gtk.Label(label="It runs:", xalign=0, css_classes=["heading"]))
        box.append(self.sql)
        tv.set_content(Gtk.ScrolledWindow(child=box, propagate_natural_height=True, max_content_height=640,
                                          hscrollbar_policy=Gtk.PolicyType.NEVER))
        self.set_child(tv)
        follow_content(self, 560)
        self._update()

    # building blocks
    def _entry(self, title, text=""):
        e = Adw.EntryRow(title=title, text=text)
        e.connect("changed", lambda *_: self._update())
        self.g.add(e)
        return e

    def _pick(self, title, items, sub=""):
        r = Adw.ComboRow(title=title, subtitle=sub, model=Gtk.StringList.new(items))
        r.connect("notify::selected", lambda *_: self._update())
        self.g.add(r)
        return r

    def _switch(self, title, active=False):
        s = Adw.SwitchRow(title=title, active=active)
        s.connect("notify::active", lambda *_: self._update())
        self.g.add(s)
        return s

    def _build_table(self):
        self.name = self._entry("Table name")
        self.cols_g = Adw.PreferencesGroup(title="Columns")
        add = Gtk.Button(label="Add column", valign=Gtk.Align.CENTER)
        add.connect("clicked", lambda *_: self._col_row())
        self.cols_g.set_header_suffix(add)
        self.g.get_parent().append(self.cols_g)
        self._col_row("id", self._int_type(), pk=True)
        self._col_row("name", TYPES[self.b.kind][0])

    def _int_type(self):
        return "bigint"

    def _col_row(self, name="", ctype=None, pk=False):
        types = TYPES[self.b.kind]
        row = Adw.ExpanderRow(title=name or "new_column", expanded=not name)
        e = Adw.EntryRow(title="Name", text=name)
        t = Adw.ComboRow(title="Type", model=Gtk.StringList.new(types))
        if ctype in types:
            t.set_selected(types.index(ctype))
        n = Adw.SwitchRow(title="Can be empty (NULL)", active=not pk)
        p = Adw.SwitchRow(title="Primary key", active=pk)
        rm = Gtk.Button(icon_name="user-trash-symbolic", tooltip_text="Remove this column", valign=Gtk.Align.CENTER)
        rm.add_css_class("flat")
        row.add_suffix(rm)
        for w in (e, t, n, p):
            row.add_row(w)
            w.connect("notify::selected" if w is t else "notify::active" if w in (n, p) else "changed",
                      lambda *_: self._update())
        e.connect("changed", lambda *_: row.set_title(e.get_text() or "new_column"))
        rec = (row, e, t, n, p)
        rm.connect("clicked", lambda *_: (self.cols_g.remove(row), self.rows.remove(rec), self._update()))
        self.rows.append(rec)
        self.cols_g.add(row)
        self._update()

    def _build_add(self):
        self.name = self._entry("Column name")
        self.type = self._pick("Type", TYPES[self.b.kind])
        self.null = self._switch("Can be empty (NULL)", True)
        self.default = self._entry("Default (SQL, optional — e.g. 0, 'x', now())")

    def _build_rename(self):
        self.col = self._pick("Column", self.columns)
        self.name = self._entry("New name")

    def _build_drop(self):
        self.col = self._pick("Column", self.columns, "Its data is deleted for every row")

    def _build_index(self):
        self.name = self._entry("Index name", f"{self._table_name()}_idx")
        self.unique = self._switch("Unique (no two rows with the same values)")
        self.idx_cols = []
        for c in self.columns:
            s = self._switch(c)
            self.idx_cols.append((c, s))

    def _table_name(self):
        n = self.ex.node
        return (n.ref[1] if isinstance(n.ref, tuple) else n.ref) if n is not None else "table"

    # SQL
    def _statement(self):
        b, a = self.b, self.action
        if a == "table":
            name = self.name.get_text().strip()
            cols = [(e.get_text().strip(), TYPES[b.kind][t.get_selected()], n.get_active(), p.get_active())
                    for _r, e, t, n, p in self.rows if e.get_text().strip()]
            return (create_table(b, schema_of(b, self.ex.node), name, cols), None) if name and cols else \
                (None, "Give the table a name and at least one column")
        table = table_sql(b, self.ex.node)
        if a == "add":
            name = self.name.get_text().strip()
            if not name:
                return None, "Name the column"
            return add_column(b, table, name, TYPES[b.kind][self.type.get_selected()], self.null.get_active(),
                              self.default.get_text().strip()), None
        if a == "rename":
            new = self.name.get_text().strip()
            if not new or not self.columns:
                return None, "Type the new name"
            return rename_column(b, table, self.columns[self.col.get_selected()], new), None
        if a == "drop":
            return (drop_column(b, table, self.columns[self.col.get_selected()]), None) if self.columns else \
                (None, "No columns")
        if a == "index":
            cols = [c for c, s in self.idx_cols if s.get_active()]
            name = self.name.get_text().strip()
            return (add_index(b, table, name, cols, self.unique.get_active()), None) if cols and name else \
                (None, "Name the index and pick its columns")
        return None, ""

    def _update(self):
        if not hasattr(self, "sql"):
            return
        sql, why = self._statement()
        self.sql.set_text(sql or why)
        self.go.set_sensitive(bool(sql) and self.ex.allow)
        if not self.ex.allow:
            self.sql.set_text((sql or why) + "\n\n— Switch on “Allow changes” in the explorer to run it.")

    def _run(self):
        sql, _why = self._statement()
        if not sql:
            return
        self.go.set_sensitive(False)

        def done(_r):
            self.close()
            self.ex.win.toast("Done")
            self.ex.reload()
            if self.action != "table":
                self.ex._load_struct()

        def fail(e):
            self.go.set_sensitive(True)
            self.sql.set_text(f"{sql}\n\nFailed: {e}")
        bg(self.b.query, sql, True, done=done, error=fail)
